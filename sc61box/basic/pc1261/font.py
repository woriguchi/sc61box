def glyph(ch: str) -> bytes | None:
    """字の形の5列(1バイトが縦の1列、ビット0が上)。描いていない字はNone"""
    rows = FONT.get(ch)
    if rows is None:
        return None
    return bytes(sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5))
