def glyph(ch: str) -> bytes:
    """字の形の5列(1バイトが縦の1列、ビット0が上)。描いていない字は空白"""
    rows = FONT.get(ch)
    if rows is None:
        return bytes(5)
    return bytes(sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5))


